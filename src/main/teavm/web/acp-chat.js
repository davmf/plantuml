// Chat with a local agent (Claude through its ACP adapter) in the SysML
// playground. The page is the ACP client; tools/acp-bridge/acp-bridge.mjs
// spawns the agent and carries the JSON-RPC: Server-Sent Events from the
// agent, POST to it. Served by a plain static server, /acp/status does not
// answer and the chat stays hidden.
//
// The agent works in the bridge's workspace directory, not on the page: each
// prompt can attach the open SysML files and the PlantUML pane, and the code
// blocks of its answers have buttons that put them into the editors.
//
// Everything the agent sends is shown with textContent, never as HTML.

const OPEN_KEY = "plantuml-sysml-chat-open";
const PROTOCOL_VERSION = 1;
// "Manual" in the Claude adapter: every edit and command asks first
const PREFERRED_MODE = "default";
// Model, effort... as last chosen, set again on every new session
const CONFIG_KEY = "plantuml-sysml-chat-config";
// Session options not shown in the options row
const HIDDEN_CONFIG = new Set(["mode", "agent"]);

function loadSavedConfig() {
	try {
		const saved = JSON.parse(localStorage.getItem(CONFIG_KEY));
		return saved != null && typeof saved === "object" ? saved : {};
	} catch (err) {
		return {};
	}
}

const INTRO = "You are assisting in the PlantUML SysML import playground (a web page). "
	+ "The page has SysML v2 files on the left, the PlantUML they import into in the middle "
	+ "(generated by !include_sysml, or a diagram written by hand), and the rendered diagram on the right. "
	+ "The current editor contents are attached as resources when the user allows it. "
	+ "When you propose a SysML file or a PlantUML diagram, give the WHOLE file in one fenced code block "
	+ "tagged ```sysml or ```plantuml: the page has buttons that put such a block into its editors. "
	+ "A SysML tab the user has saved is a file of the same name in your working directory: to change it, "
	+ "edit that file with your tools; the page shows the edit in the tab at once (the user can undo it). "
	+ "A new .sysml file you create there opens as a new tab. Tabs not saved exist only in the browser: "
	+ "propose those as fenced blocks instead. The PlantUML pane is never a file.";

/**
 * host: {
 *   context(): {files: [{name, text}], active, puml, mode, status},
 *   newSysmlTab(text), replaceSysml(text), setPlantUml(text), toast(message, isError)
 * }
 */
export async function createAcpChat(host) {
	const toggle = document.getElementById("chat-toggle");
	const pane = document.getElementById("chat-pane");
	if (toggle == null || pane == null) {
		return;
	}
	let status;
	try {
		const res = await fetch("acp/status", {cache: "no-store"});
		status = res.ok ? await res.json() : null;
	} catch (err) {
		status = null;
	}
	if (status == null || status.available !== true) {
		return; // a static server: no bridge, no chat
	}
	new AcpChat(host, toggle, pane, status).start();
}

class AcpChat {
	constructor(host, toggle, pane, status) {
		this.host = host;
		this.toggle = toggle;
		this.pane = pane;
		this.bridge = status;
		this.log = pane.querySelector(".chat-log");
		this.input = pane.querySelector(".chat-input");
		this.sendButton = pane.querySelector(".chat-send");
		this.stopButton = pane.querySelector(".chat-stop");
		this.modeSelect = pane.querySelector(".chat-mode");
		this.configEl = pane.querySelector(".chat-config");
		this.configOptions = null;
		this.contextBox = pane.querySelector(".chat-context");
		this.stateEl = pane.querySelector(".chat-state");

		this.source = null;      // EventSource
		this.token = null;
		this.nextId = 1;
		this.pending = new Map(); // id -> {resolve, reject}
		this.sessionId = null;
		this.connecting = null;   // Promise of the session
		this.busy = false;
		this.introduced = false;
		this.agentMessage = null; // {el, text} of the answer being streamed
		this.thought = null;
		this.toolCalls = new Map();
	}

	start() {
		this.toggle.hidden = false;
		this.toggle.addEventListener("click", () => this.setOpen(this.pane.hidden));
		this.pane.querySelector(".chat-close").addEventListener("click", () => this.setOpen(false));
		this.pane.querySelector(".chat-new").addEventListener("click", () => this.restart());
		this.sendButton.addEventListener("click", () => this.send());
		this.stopButton.addEventListener("click", () => this.cancel());
		// Enter sends; Alt+Enter (or Shift+Enter) starts a new line
		this.input.addEventListener("keydown", e => {
			if (e.key !== "Enter" || e.isComposing || e.shiftKey) {
				return;
			}
			e.preventDefault();
			if (e.altKey) {
				const start = this.input.selectionStart;
				this.input.setRangeText("\n", start, this.input.selectionEnd, "end");
				this.input.dispatchEvent(new Event("input"));
			} else {
				this.send();
			}
		});
		this.modeSelect.addEventListener("change", () => this.setMode(this.modeSelect.value));
		this.setOpen(localStorage.getItem(OPEN_KEY) === "true");
		this.updateButtons();
	}

	setOpen(open) {
		this.pane.hidden = open === false;
		document.body.classList.toggle("chat-open", open);
		this.toggle.setAttribute("aria-pressed", open ? "true" : "false");
		localStorage.setItem(OPEN_KEY, open ? "true" : "false");
		if (open) {
			this.input.focus();
			this.ensureSession().catch(() => {});
		}
	}

	setState(text, isError = false) {
		this.stateEl.textContent = text;
		this.stateEl.classList.toggle("error", isError);
	}

	updateButtons() {
		this.sendButton.hidden = this.busy;
		this.stopButton.hidden = this.busy === false;
	}

	// -----------------------------------------------------------------------
	// Transport
	// -----------------------------------------------------------------------

	// Opens the stream (one agent process per stream) and resolves on hello.
	connect() {
		return new Promise((resolve, reject) => {
			const source = new EventSource("acp/events");
			this.source = source;
			let opened = false;
			source.addEventListener("hello", e => {
				opened = true;
				this.token = JSON.parse(e.data).token;
				resolve();
			});
			source.addEventListener("message", e => this.receive(e.data));
			source.addEventListener("agent-exit", e => {
				const info = JSON.parse(e.data);
				this.disconnect("The agent stopped" + (info.error ? ": " + info.error : info.code != null ? " (exit " + info.code + ")" : ""));
			});
			source.onerror = () => {
				if (opened === false) {
					source.close();
					reject(new Error("cannot reach the ACP bridge"));
				} else if (source.readyState === EventSource.CLOSED || this.source === source) {
					// Never let EventSource reconnect on its own: that would spawn a new agent
					this.disconnect("Lost the connection to the ACP bridge");
				}
			};
		});
	}

	disconnect(reason) {
		if (this.source != null) {
			this.source.close();
		}
		this.source = null;
		this.token = null;
		this.sessionId = null;
		this.connecting = null;
		this.introduced = false;
		for (const {reject} of this.pending.values()) {
			reject(new Error(reason || "disconnected"));
		}
		this.pending.clear();
		this.endTurn();
		if (reason) {
			this.setState(reason + ". Send again to restart it.", true);
		}
	}

	async post(message) {
		const res = await fetch("acp/send?c=" + encodeURIComponent(this.token), {
			method: "POST",
			headers: {"Content-Type": "application/json"},
			body: JSON.stringify(message),
		});
		if (res.ok === false) {
			let error = res.status + "";
			try {
				error = (await res.json()).error || error;
			} catch (err) {
				// keep the status
			}
			throw new Error(error);
		}
	}

	request(method, params) {
		const id = this.nextId++;
		return new Promise((resolve, reject) => {
			this.pending.set(id, {resolve, reject});
			this.post({jsonrpc: "2.0", id, method, params}).catch(err => {
				this.pending.delete(id);
				reject(err);
			});
		});
	}

	notify(method, params) {
		return this.post({jsonrpc: "2.0", method, params});
	}

	respond(id, result, error) {
		const message = {jsonrpc: "2.0", id};
		if (error != null) {
			message.error = error;
		} else {
			message.result = result;
		}
		return this.post(message).catch(err => console.warn("ACP response failed:", err));
	}

	receive(line) {
		let message;
		try {
			message = JSON.parse(line);
		} catch (err) {
			console.warn("ACP: not JSON:", line);
			return;
		}
		if (message.method == null) {
			const waiting = this.pending.get(message.id);
			if (waiting != null) {
				this.pending.delete(message.id);
				if (message.error != null) {
					waiting.reject(new Error(message.error.message || JSON.stringify(message.error)));
				} else {
					waiting.resolve(message.result);
				}
			}
			return;
		}
		if (message.id != null) {
			this.agentRequest(message);
		} else if (message.method === "session/update") {
			this.update(message.params.update);
		}
	}

	// The client methods the agent may call: only permissions here. File
	// system and terminal are not offered in initialize, so the agent uses
	// its own tools in the bridge's workspace.
	agentRequest(message) {
		if (message.method === "session/request_permission") {
			this.askPermission(message.id, message.params);
			return;
		}
		this.respond(message.id, null, {code: -32601, message: "Method not supported by the playground: " + message.method});
	}

	// -----------------------------------------------------------------------
	// Session
	// -----------------------------------------------------------------------

	ensureSession() {
		if (this.connecting == null) {
			this.connecting = this.openSession().catch(err => {
				this.disconnect();
				this.setState(err.message, true);
				throw err;
			});
		}
		return this.connecting;
	}

	async openSession() {
		this.setState("Starting the agent…");
		await this.connect();
		const init = await this.request("initialize", {
			protocolVersion: PROTOCOL_VERSION,
			clientCapabilities: {fs: {readTextFile: false, writeTextFile: false}, terminal: false},
			clientInfo: {name: "plantuml-sysml-playground", version: "1"},
		});
		this.promptCapabilities = (init && init.agentCapabilities && init.agentCapabilities.promptCapabilities) || {};
		const agentName = (init && init.agentInfo && (init.agentInfo.title || init.agentInfo.name)) || "agent";
		// The bridge sets cwd to its workspace whatever is sent
		const session = await this.request("session/new", {cwd: this.bridge.cwd, mcpServers: []});
		this.sessionId = session.sessionId;
		this.showModes(session.modes);
		this.showConfig(session.configOptions);
		if (session.modes != null && session.modes.currentModeId !== PREFERRED_MODE
			&& session.modes.availableModes.some(m => m.id === PREFERRED_MODE)) {
			await this.setMode(PREFERRED_MODE);
		}
		await this.restoreConfig();
		this.setState(agentName + " · workspace " + this.bridge.cwd);
		return this.sessionId;
	}

	// The agent's session options (model, effort...) as selects, from what it
	// reports: the list changes with the model (Opus adds "fast"). The mode
	// has its own select in the title, and "agent" picks a subagent persona.
	showConfig(configOptions) {
		if (Array.isArray(configOptions) === false) {
			return;
		}
		this.configOptions = configOptions;
		this.configEl.replaceChildren();
		for (const option of configOptions) {
			if (HIDDEN_CONFIG.has(option.id) || option.type !== "select" || Array.isArray(option.options) === false) {
				continue;
			}
			const label = document.createElement("label");
			label.title = option.description || option.name;
			label.append(option.name.toLowerCase() + " ");
			const select = document.createElement("select");
			for (const choice of option.options) {
				const el = document.createElement("option");
				el.value = choice.value;
				el.textContent = choice.name;
				el.title = choice.description || "";
				select.appendChild(el);
			}
			select.value = option.currentValue;
			select.addEventListener("change", () => {
				this.rememberConfig(option.id, select.value);
				this.setConfig(option.id, select.value);
			});
			label.appendChild(select);
			this.configEl.appendChild(label);
		}
		this.configEl.hidden = this.configEl.childElementCount === 0;
	}

	async setConfig(configId, value) {
		if (this.sessionId == null) {
			return;
		}
		try {
			const result = await this.request("session/set_config_option", {sessionId: this.sessionId, configId, value});
			this.showConfig(result && result.configOptions);
		} catch (err) {
			this.host.toast("Could not set " + configId + ": " + err.message, true);
			this.showConfig(this.configOptions);
		}
	}

	rememberConfig(configId, value) {
		const saved = loadSavedConfig();
		saved[configId] = value;
		localStorage.setItem(CONFIG_KEY, JSON.stringify(saved));
	}

	// The model first: it decides which other options exist.
	async restoreConfig() {
		const saved = loadSavedConfig();
		const ids = Object.keys(saved).sort((a, b) => (b === "model") - (a === "model"));
		for (const id of ids) {
			const option = (this.configOptions || []).find(o => o.id === id);
			if (option != null && option.currentValue !== saved[id]
				&& (option.options || []).some(c => c.value === saved[id])) {
				await this.setConfig(id, saved[id]);
			}
		}
	}

	showModes(modes) {
		this.modeSelect.replaceChildren();
		if (modes == null) {
			this.modeSelect.hidden = true;
			return;
		}
		for (const mode of modes.availableModes) {
			const option = document.createElement("option");
			option.value = mode.id;
			option.textContent = mode.name;
			option.title = mode.description || "";
			this.modeSelect.appendChild(option);
		}
		this.modeSelect.value = modes.currentModeId;
		this.modeSelect.hidden = false;
	}

	async setMode(modeId) {
		if (this.sessionId == null) {
			return;
		}
		try {
			await this.request("session/set_mode", {sessionId: this.sessionId, modeId});
			this.modeSelect.value = modeId;
		} catch (err) {
			this.host.toast("Mode change failed: " + err.message, true);
		}
	}

	restart() {
		if (this.busy && confirm("Stop the current answer and start a new chat?") === false) {
			return;
		}
		this.disconnect();
		this.log.replaceChildren();
		this.toolCalls.clear();
		this.ensureSession().catch(() => {});
	}

	// -----------------------------------------------------------------------
	// Prompting
	// -----------------------------------------------------------------------

	async send() {
		const text = this.input.value.trim();
		if (text === "" || this.busy) {
			return;
		}
		this.input.value = "";
		this.addBubble("user", text);
		this.busy = true;
		this.updateButtons();
		try {
			const sessionId = await this.ensureSession();
			const result = await this.request("session/prompt", {sessionId, prompt: this.promptBlocks(text)});
			if (result && result.stopReason && result.stopReason !== "end_turn") {
				this.addNote("Stopped: " + result.stopReason.replace(/_/g, " "));
			}
		} catch (err) {
			this.addNote("Error: " + err.message, true);
		} finally {
			this.endTurn();
		}
	}

	endTurn() {
		this.busy = false;
		this.agentMessage = null;
		this.thought = null;
		this.updateButtons();
	}

	cancel() {
		if (this.sessionId != null && this.busy) {
			this.notify("session/cancel", {sessionId: this.sessionId}).catch(() => {});
		}
	}

	promptBlocks(text) {
		const blocks = [];
		if (this.introduced === false) {
			blocks.push({type: "text", text: INTRO});
			this.introduced = true;
		}
		if (this.contextBox.checked) {
			const context = this.host.context();
			const embed = this.promptCapabilities.embeddedContext === true;
			const attach = (uri, body, label) => {
				if (embed) {
					blocks.push({type: "resource", resource: {uri, mimeType: "text/plain", text: body}});
				} else {
					blocks.push({type: "text", text: label + " (" + uri + "):\n```\n" + body + "\n```"});
				}
			};
			context.files.forEach((file, index) => {
				attach("playground:sysml/" + encodeURIComponent(file.name), file.text,
					"SysML file " + file.name + (index === context.active ? " (the active tab)" : ""));
			});
			attach("playground:plantuml", context.puml,
				"PlantUML pane (" + (context.mode === "directive" ? "a diagram with !include_sysml" : "generated by the import") + ")");
			const saved = context.files.filter(f => f.disk !== undefined).map(f =>
				f.name + (f.text === f.disk ? "" : " (the browser has unsaved edits; the attachment is the browser's text)"));
			blocks.push({type: "text", text: (saved.length > 0
				? "Tabs saved in your working directory: " + saved.join(", ") + ". "
				: "No tab is saved in your working directory. ")
				+ "Active SysML tab: " + context.files[context.active].name
				+ ". Middle pane mode: " + context.mode + "."
				+ (context.status ? " Import status: " + context.status : "")});
		}
		blocks.push({type: "text", text});
		return blocks;
	}

	// -----------------------------------------------------------------------
	// Session updates
	// -----------------------------------------------------------------------

	update(update) {
		if (update == null) {
			return;
		}
		switch (update.sessionUpdate) {
			case "agent_message_chunk":
				this.thought = null;
				if (update.content && update.content.type === "text") {
					if (this.agentMessage == null) {
						const el = this.addBubble("agent", "");
						this.agentMessage = {el, text: ""};
					}
					this.agentMessage.text += update.content.text;
					this.renderMarkdown(this.agentMessage.el, this.agentMessage.text);
				}
				break;
			case "agent_thought_chunk":
				if (update.content && update.content.type === "text") {
					if (this.thought == null) {
						const details = document.createElement("details");
						details.className = "chat-thought";
						const summary = document.createElement("summary");
						summary.textContent = "Thinking";
						const body = document.createElement("div");
						details.append(summary, body);
						this.append(details);
						this.thought = {el: body, text: ""};
					}
					this.thought.text += update.content.text;
					this.thought.el.textContent = this.thought.text;
				}
				break;
			case "tool_call":
			case "tool_call_update":
				this.agentMessage = null;
				this.thought = null;
				this.showToolCall(update);
				break;
			case "plan":
				this.showPlan(update.entries || []);
				break;
			case "current_mode_update":
				this.modeSelect.value = update.currentModeId;
				break;
			case "config_option_update":
				this.showConfig(update.configOptions);
				break;
			default:
				break;
		}
	}

	showToolCall(update) {
		let entry = this.toolCalls.get(update.toolCallId);
		if (entry == null) {
			const el = document.createElement("div");
			el.className = "chat-tool";
			const title = document.createElement("span");
			title.className = "chat-tool-title";
			const state = document.createElement("span");
			state.className = "chat-tool-status";
			el.append(state, title);
			this.append(el);
			entry = {el, title, state};
			this.toolCalls.set(update.toolCallId, entry);
		}
		if (update.title) {
			entry.title.textContent = update.title;
		}
		if (update.status) {
			entry.el.dataset.status = update.status;
			entry.state.textContent = {pending: "…", in_progress: "⟳", completed: "✓", failed: "✗"}[update.status] || "•";
			entry.state.title = update.status.replace(/_/g, " ");
		}
	}

	showPlan(entries) {
		if (this.planEl == null || this.planEl.isConnected === false) {
			this.planEl = document.createElement("ol");
			this.planEl.className = "chat-plan";
			this.append(this.planEl);
		}
		this.planEl.replaceChildren(...entries.map(entry => {
			const li = document.createElement("li");
			li.textContent = entry.content;
			li.dataset.status = entry.status;
			return li;
		}));
	}

	askPermission(id, params) {
		const box = document.createElement("div");
		box.className = "chat-permission";
		const title = document.createElement("div");
		title.textContent = "Allow: " + ((params.toolCall && params.toolCall.title) || "an action of the agent") + "?";
		box.appendChild(title);
		const raw = params.toolCall && params.toolCall.rawInput;
		if (raw != null) {
			const pre = document.createElement("pre");
			pre.textContent = typeof raw === "string" ? raw : JSON.stringify(raw, null, 2);
			box.appendChild(pre);
		}
		const buttons = document.createElement("div");
		buttons.className = "chat-actions";
		const answer = (outcome, label) => {
			buttons.remove();
			const done = document.createElement("div");
			done.className = "chat-note";
			done.textContent = label;
			box.appendChild(done);
			this.respond(id, {outcome});
		};
		for (const option of params.options || []) {
			const button = document.createElement("button");
			button.type = "button";
			button.textContent = option.name;
			button.dataset.kind = option.kind || "";
			button.addEventListener("click", () => answer({outcome: "selected", optionId: option.optionId}, option.name));
			buttons.appendChild(button);
		}
		const cancel = document.createElement("button");
		cancel.type = "button";
		cancel.textContent = "Cancel";
		cancel.addEventListener("click", () => answer({outcome: "cancelled"}, "Cancelled"));
		buttons.appendChild(cancel);
		box.appendChild(buttons);
		this.append(box);
		if (this.pane.hidden) {
			this.setOpen(true);
		}
	}

	// -----------------------------------------------------------------------
	// Rendering
	// -----------------------------------------------------------------------

	append(el) {
		const atBottom = this.log.scrollHeight - this.log.scrollTop - this.log.clientHeight < 40;
		this.log.appendChild(el);
		if (atBottom) {
			this.log.scrollTop = this.log.scrollHeight;
		}
	}

	addBubble(who, text) {
		const el = document.createElement("div");
		el.className = "chat-msg chat-" + who;
		el.textContent = text;
		this.append(el);
		return el;
	}

	addNote(text, isError = false) {
		const el = document.createElement("div");
		el.className = "chat-note" + (isError ? " error" : "");
		el.textContent = text;
		this.append(el);
	}

	// Paragraphs as text, fenced code blocks with buttons into the editors.
	renderMarkdown(el, text) {
		const atBottom = this.log.scrollHeight - this.log.scrollTop - this.log.clientHeight < 40;
		el.replaceChildren();
		let prose = [];
		let code = null; // {lang, lines} inside a fence
		const flushProse = () => {
			if (prose.join("").trim() !== "") {
				el.appendChild(this.textPart(prose.join("\n")));
			}
			prose = [];
		};
		for (const line of text.split("\n")) {
			if (code == null) {
				const open = /^\s*```\s*([\w+-]*)/.exec(line);
				if (open != null) {
					flushProse();
					code = {lang: open[1].toLowerCase(), lines: []};
				} else {
					prose.push(line);
				}
			} else if (/^\s*```\s*$/.test(line)) {
				el.appendChild(this.codePart(code.lang, code.lines.join("\n"), true));
				code = null;
			} else {
				code.lines.push(line);
			}
		}
		if (code != null) {
			el.appendChild(this.codePart(code.lang, code.lines.join("\n"), false));
		}
		flushProse();
		if (atBottom) {
			this.log.scrollTop = this.log.scrollHeight;
		}
	}

	textPart(text) {
		const div = document.createElement("div");
		div.className = "chat-text";
		div.textContent = text.replace(/^\n+|\n+$/g, "");
		return div;
	}

	codePart(lang, code, closed) {
		const wrap = document.createElement("div");
		wrap.className = "chat-code";
		const pre = document.createElement("pre");
		pre.textContent = code;
		wrap.appendChild(pre);
		if (closed === false) {
			return wrap; // still streaming
		}
		const isPlantUml = lang === "plantuml" || lang === "puml" || /^\s*@start\w+/m.test(code);
		const isSysml = isPlantUml === false && (lang === "sysml" || lang === "kerml" || /\b(package|part def|port def)\b/.test(code));
		const actions = document.createElement("div");
		actions.className = "chat-actions";
		const button = (label, title, action) => {
			const b = document.createElement("button");
			b.type = "button";
			b.textContent = label;
			b.title = title;
			b.addEventListener("click", action);
			actions.appendChild(b);
		};
		if (isSysml) {
			button("New SysML tab", "Open this block as a new SysML file", () => this.host.newSysmlTab(code));
			button("Replace SysML tab", "Replace the active SysML tab with this block", () => this.host.replaceSysml(code));
		}
		if (isPlantUml) {
			button("To PlantUML pane", "Put this block in the middle pane and render it", () => this.host.setPlantUml(code));
		}
		button("Copy", "Copy this block", () => navigator.clipboard.writeText(code).then(
			() => this.host.toast("Copied"),
			err => this.host.toast("Copy failed: " + err, true)));
		wrap.appendChild(actions);
		return wrap;
	}
}
